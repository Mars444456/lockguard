const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
require('./check-privacy').assertPublishable(root);
const file = path.join(root, 'docs/index.html');
const html = fs.readFileSync(file, 'utf8');
const section = /<section id="pricing"[\s\S]*?<\/section>/;
if (!section.test(html)) throw new Error('Public pricing section not found');
const pricing = fs.readFileSync(path.join(root, 'src/ui/free-beta-pricing.html'), 'utf8').trim();
fs.writeFileSync(file, html.replace(section, () => pricing));
require('./build-site-links').buildSiteLinks();
require('./build-i18n').buildI18n();
require('./check-privacy').assertPublishable(root);
console.log('Public free beta page updated.');
